UPDATE farm_blocks block
SET description = exact_block.description,
    early_block_classification = exact_block.early_block_classification,
    early_harvest = exact_block.early_block_classification = 'Yes',
    shoot_maturity = exact_block.shoot_maturity,
    year_planted = NULL,
    size_acres = NULL,
    variety = NULL,
    forecast_yield_kg = NULL,
    fruit_fly_pressure = exact_block.fruit_fly_pressure,
    disease_rating = exact_block.disease_rating,
    soil_notes = NULL,
    planting_started_on = NULL,
    status = 'active',
    source = 'Farm Management  Data Records.xlsx',
    updated_at = now()
FROM exact_block
JOIN farms farm ON farm.farm_code = exact_block.farm_code
WHERE block.farm_id = farm.id
  AND block.block_code = exact_block.block_code;

-- The earlier import created zero-count variety rows for blank Variety/Tree cells.
-- Close only those empty inferred rows; real inventory records remain untouched.
UPDATE block_crop_inventories inventory
SET effective_to = CURRENT_DATE,
    updated_at = now()
FROM farm_blocks block
JOIN farms farm ON farm.id = block.farm_id
WHERE inventory.block_id = block.id
  AND inventory.effective_to IS NULL
  AND inventory.total_trees = 0
  AND inventory.productive_trees = 0
  AND inventory.non_productive_trees = 0
  AND inventory.dead_trees = 0
  AND farm.farm_code IN ('FARM-LAND-A', 'FARM-LAND-B')
  AND block.block_code IN ('A1', 'A2', 'A3', 'A4', 'A5', 'A6', 'B1', 'B2', 'B3', 'B4', 'B5');

-- A6 was generated by a routine check, but the supplied Farm Land A table ends at A5.
-- Keep it as archived history instead of exposing it as a current workbook block.
UPDATE farm_blocks block
SET status = 'archived',
    updated_at = now()
FROM farms farm
WHERE block.farm_id = farm.id
  AND farm.farm_code = 'FARM-LAND-A'
  AND block.block_code = 'A6'
  AND block.status <> 'archived';

INSERT INTO block_status_history (
