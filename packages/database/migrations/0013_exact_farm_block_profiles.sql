-- Preserve the farm block table exactly as recorded in the workbook. Blank workbook
-- cells remain NULL so administrators can complete them later without inferred data.

ALTER TABLE farm_blocks ADD COLUMN IF NOT EXISTS description text;
ALTER TABLE farm_blocks ADD COLUMN IF NOT EXISTS early_block_classification text;
ALTER TABLE farm_blocks ADD COLUMN IF NOT EXISTS year_planted integer;

ALTER TABLE farm_blocks ALTER COLUMN forecast_yield_kg DROP DEFAULT;
ALTER TABLE farm_blocks ALTER COLUMN forecast_yield_kg DROP NOT NULL;
ALTER TABLE farm_blocks ALTER COLUMN fruit_fly_pressure DROP DEFAULT;
ALTER TABLE farm_blocks ALTER COLUMN fruit_fly_pressure DROP NOT NULL;
ALTER TABLE farm_blocks ALTER COLUMN disease_rating DROP DEFAULT;
ALTER TABLE farm_blocks ALTER COLUMN disease_rating DROP NOT NULL;

ALTER TABLE farm_blocks DROP CONSTRAINT IF EXISTS farm_blocks_year_planted_check;
ALTER TABLE farm_blocks ADD CONSTRAINT farm_blocks_year_planted_check
  CHECK (year_planted IS NULL OR year_planted BETWEEN 1900 AND 2200) NOT VALID;

WITH exact_block (
  farm_code, block_code, description, early_block_classification,
  shoot_maturity, fruit_fly_pressure, disease_rating
) AS (
  VALUES
    ('FARM-LAND-A', 'A1', 'Farm close to the road. It boarders the Cashew Farm', 'Yes', 1.0::real, 'Medium', 'Medium'),
    ('FARM-LAND-A', 'A2', 'Where Ante Mansa Farms', 'Mid', 0.7::real, 'Medium', 'Medium'),
    ('FARM-LAND-A', 'A3', 'Togbuis farming area', 'Mid', 0.7::real, 'Medium', 'Medium'),
    ('FARM-LAND-A', 'A4', 'Land Purchased from Amoateng', 'New', 0.0::real, 'Medium', 'Medium'),
    ('FARM-LAND-A', 'A5', 'New', 'New', 0.0::real, 'NA', 'NA'),
    ('FARM-LAND-B', 'B1', 'Osofo''s Farms', 'Mid', 0.7::real, 'Medium', 'Medium'),
    ('FARM-LAND-B', 'B2', 'Ananes Farms', 'Mid', 0.5::real, 'Medium', 'Medium'),
    ('FARM-LAND-B', 'B3', 'Kwaku Boakyes Farm', 'Mid', 0.6::real, 'Medium', 'Medium'),
    ('FARM-LAND-B', 'B4', 'Where the Oil Palm is', 'New', 0.0::real, 'Medium', 'Medium'),
