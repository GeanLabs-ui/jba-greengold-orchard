)
SELECT
  'xlsx-2026-block-a6-archive', block.id, 'archived', 'active', 'archived',
  'Excluded from the current profile because the supplied Farm Land A table ends at A5.',
  CURRENT_DATE, NULL
FROM farm_blocks block
JOIN farms farm ON farm.id = block.farm_id
WHERE farm.farm_code = 'FARM-LAND-A' AND block.block_code = 'A6'
